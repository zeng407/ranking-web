        <h2>{{ translate(locale, 'communityHighlights') }}</h2>
      </div>
    </div>

    <div class="highlight-carousel-shell">
      <button
        v-if="carouselItems.length > 1"
        class="highlight-carousel-arrow is-previous"
        type="button"
        :aria-label="translate(locale, 'previousPage')"
        @click="showPreviousCarouselItem"
      >
        <svg viewBox="0 0 24 24" aria-hidden="true"><path d="m15 5-7 7 7 7" /></svg>
      </button>
      <article :key="`${activeCarouselIndex}-${activeCarouselItem.video_id || activeCarouselItem.image_url}`" class="highlight-carousel-card">
        <div class="highlight-carousel-media">
          <iframe
            v-if="carouselYoutubeEmbedURL(activeCarouselItem)"
            :src="carouselYoutubeEmbedURL(activeCarouselItem) || ''"
            :title="activeCarouselItem.title || 'YouTube video'"
            allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
            referrerpolicy="strict-origin-when-cross-origin"
            allowfullscreen
          />
          <a
            v-else-if="activeCarouselItem.image_url && activeCarouselItem.video_url"
            :href="activeCarouselItem.video_url"
            target="_blank"
            rel="noopener noreferrer"
          >
            <img :src="activeCarouselItem.image_url" :alt="activeCarouselItem.title || ''">
          </a>
          <img
            v-else-if="activeCarouselItem.image_url"
            :src="activeCarouselItem.image_url"
            :alt="activeCarouselItem.title || ''"
          >
        </div>
        <div v-if="activeCarouselItem.title || activeCarouselItem.description" class="highlight-carousel-copy">
          <h3 v-if="activeCarouselItem.title">{{ activeCarouselItem.title }}</h3>
          <p v-if="activeCarouselItem.description && activeCarouselItem.description !== activeCarouselItem.title">
            {{ activeCarouselItem.description }}
          </p>
        </div>
      </article>
      <button
        v-if="carouselItems.length > 1"
        class="highlight-carousel-arrow is-next"
        type="button"
        :aria-label="translate(locale, 'nextPage')"
        @click="showNextCarouselItem"
      >
        <svg viewBox="0 0 24 24" aria-hidden="true"><path d="m9 5 7 7-7 7" /></svg>
      </button>
    </div>

    <div v-if="carouselItems.length > 1" class="highlight-carousel-position">
      <span>{{ activeCarouselIndex + 1 }} / {{ carouselItems.length }}</span>
      <div class="highlight-dots" role="group" :aria-label="translate(locale, 'communityHighlights')">
        <button
          v-for="(item, index) in carouselItems"
          :key="`${item.video_id || item.image_url}-${index}`"
          type="button"
          :class="{ active: activeCarouselIndex === index }"
          :aria-label="`${index + 1}: ${item.title || ''}`"
          :aria-current="activeCarouselIndex === index ? 'true' : undefined"
          @click="activeCarouselIndex = index"
        />
      </div>
    </div>
      </section>

      <AdSlot name="homeRail" shape="rectangle" :locale="locale" />

      <section v-if="champions.length" class="champion-marquee-section" :aria-label="translate(locale, 'recentChampions')">
    <div class="champion-marquee-heading">
      <p class="eyebrow">{{ translate(locale, 'justFinishedEyebrow') }}</p>
      <h2>{{ translate(locale, 'recentChampions') }}</h2>
    </div>
    <div class="champion-marquee-viewport">
      <div class="champion-marquee-track">
        <RouterLink
          v-for="(champion, index) in championMarqueeItems"
          :key="`${champion.key}-${index}`"
          :to="gameURL(champion.post_serial)"
          :aria-hidden="index >= champions.length ? 'true' : undefined"
          :tabindex="index >= champions.length ? -1 : undefined"
        >
          <small class="champion-marquee-title">{{ champion.post_title }}</small>
          <span class="champion-marquee-finalists">
            <span v-if="champion.winner" class="champion-marquee-candidate is-winner">
              <video
                v-if="isVideoThumbnail(champion.winner.thumb_url)"
                :src="`${champion.winner.thumb_url}#t=0.01`"
                muted
                playsinline
                preload="metadata"
              />
              <img v-else-if="champion.winner.thumb_url" :src="champion.winner.thumb_url" :alt="champion.winner.name" loading="lazy">
              <span><em>{{ translate(locale, 'championWinner') }}</em><strong>{{ champion.winner.name }}</strong></span>
            </span>
            <b aria-hidden="true">›</b>
            <span v-if="champion.loser" class="champion-marquee-candidate is-loser">
              <video
                v-if="isVideoThumbnail(champion.loser.thumb_url)"
                :src="`${champion.loser.thumb_url}#t=0.01`"
                muted
                playsinline
                preload="metadata"
              />
              <img v-else-if="champion.loser.thumb_url" :src="champion.loser.thumb_url" :alt="champion.loser.name" loading="lazy">
              <span><em>{{ translate(locale, 'championLoser') }}</em><strong>{{ champion.loser.name }}</strong></span>
            </span>
          </span>
        </RouterLink>
      </div>
    </div>
      </section>

      <AdSlot name="homeRailBottom" shape="vertical" :locale="locale" />
    </aside>

    <section
      class="public-content-section"
      :class="{ 'is-refreshing': refreshing }"
      :aria-busy="refreshing"
      aria-live="polite"
    >
    <div v-if="refreshing" class="home-refresh-progress" role="status">
      <span aria-hidden="true" />
      <span class="sr-only">{{ translate(locale, 'loadingVotes') }}</span>
    </div>
    <form class="vote-search" role="search" @submit.prevent="submitSearch">
      <svg viewBox="0 0 24 24" aria-hidden="true"><circle cx="11" cy="11" r="7" /><path d="m20 20-4-4" /></svg>
      <input
        v-model="searchInput"
        name="k"
        type="search"
        :placeholder="translate(locale, 'searchPlaceholder')"
        :aria-label="translate(locale, 'searchVotes')"
        maxlength="255"
      >
      <button v-if="activeKeyword" class="vote-search-clear" type="button" :aria-label="translate(locale, 'clearSearch')" @click="clearSearch">×</button>
      <button class="vote-search-submit" type="submit">{{ translate(locale, 'searchVotes') }}</button>
    </form>

    <div class="section-heading section-heading-inline">
      <div>
        <p class="eyebrow">{{ translate(locale, 'discoverEyebrow') }}</p>
        <!-- The page's only h1: this is what the home page is about. -->
        <h1>{{ contentHeading }}</h1>
      </div>
      <div class="content-tabs" :aria-label="translate(locale, 'browseVotes')">
        <RouterLink :class="{ active: sort === 'hot' }" :to="browseURL('/hot')">{{ translate(locale, 'popular') }}</RouterLink>
        <RouterLink :class="{ active: sort === 'new' }" :to="browseURL('/new')">{{ translate(locale, 'latest') }}</RouterLink>
      </div>
    </div>

    <div v-if="tags.length" class="tag-strip" :aria-label="translate(locale, 'hotTopics')">
      <span>{{ translate(locale, 'hotTopics') }}</span>
      <button
        v-for="tag in tags.slice(0, 9)"
        :key="tag.name"
        class="tag-chip"
        :class="{ active: activeKeyword.toLowerCase() === tag.name.toLowerCase() }"
        type="button"
        @click="selectTag(tag.name)"
      >#{{ tag.name }}</button>
    </div>

    <AdSlot name="homeTop" shape="horizontal" :locale="locale" />

    <div v-if="loading" class="content-state">
      <span class="loading-dot" aria-hidden="true" />
      {{ translate(locale, 'loadingVotes') }}
    </div>
    <div v-else-if="loadError" class="content-state content-state-error">
      <span>{{ translate(locale, 'loadVotesError') }}</span>
      <button type="button" @click="loadPosts(true)">{{ translate(locale, 'retry') }}</button>
    </div>
    <template v-else-if="postsPage.items.length">
      <div class="vote-grid">
        <template v-for="(post, index) in postsPage.items" :key="post.serial">
        <article class="vote-card">
        <RouterLink class="vote-card-main" :to="gameURL(post.serial)">
          <div class="vote-card-media" :class="{ 'is-censored': post.is_censored > 0 }">
