<script setup lang="ts">
import { computed, ref, watch } from 'vue'
import { RouterLink, useRoute, useRouter } from 'vue-router'

import AdSlot from '../components/AdSlot.vue'
import { localizedPath, normalizeLocale, translate } from '../i18n'
import {
  carouselYoutubeEmbedURL,
  createPublicContentService,
  preferredElementImage,
  type CarouselItem,
  type Champion,
  type ChampionElement,
  type PostsPage,
  type Tag,
} from '../services/publicContent'

const route = useRoute()
const router = useRouter()
const locale = computed(() => normalizeLocale(route.params.locale))
const sort = computed<'hot' | 'new'>(() => route.path.endsWith('/new') ? 'new' : 'hot')
// Keep the public home-page query contract compatible with the original
// get-posts endpoint (`?k=...`). Accept `q` temporarily so links generated by
// the first separated-frontend build do not stop working.
const activeKeyword = computed(() => String(route.query.k || route.query.q || '').trim())
const service = createPublicContentService()
const defaultPreviewImage = '/image-placeholder.svg'

const postsPage = ref<PostsPage>({ items: [], page: 1, per_page: 15, total: 0, total_pages: 0 })
const tags = ref<Tag[]>([])
const carouselItems = ref<CarouselItem[]>([])
const champions = ref<Champion[]>([])
const loading = ref(true)
const refreshing = ref(false)
const loadingMore = ref(false)
const loadError = ref(false)
const loadMoreError = ref(false)
const activeCarouselIndex = ref(0)
const searchInput = ref(activeKeyword.value)
// One in-feed ad card per six vote cards.
const feedAdEvery = 6
let requestVersion = 0
let extrasRequestStarted = false
let lastLoadedRequestKey: string | null = null
let pendingResetRequestKey: string | null = null

const contentHeading = computed(() => activeKeyword.value
  ? `${translate(locale.value, 'searchResults')}「${activeKeyword.value}」`
  : translate(locale.value, sort.value === 'new' ? 'latestPicks' : 'popularPicks'))
const activeCarouselItem = computed(() => carouselItems.value[activeCarouselIndex.value] ?? null)
const hasMorePosts = computed(() => postsPage.value.page < postsPage.value.total_pages)

/**
 * The card indexes an in-feed ad follows.
 *
 * Every sixth card, except that AdSense allows neither ads on nor ads beside adult
 * content: a position whose card or following card is censored slides further down the
 * feed, and is dropped when the loaded feed runs out of clean neighbours.
 */
const feedAdPositions = computed<Set<number>>(() => {
  const items = postsPage.value.items
  const positions = new Set<number>()
  let anchor = feedAdEvery - 1
  while (anchor < items.length - 1) {
    let index = anchor
    const censored = (at: number): boolean => (items[at]?.is_censored ?? 0) > 0
    while (index < items.length - 1 && (censored(index) || censored(index + 1))) {
      index++
    }
    if (index >= items.length - 1) break
    positions.add(index)
    anchor = index + feedAdEvery
  }
  return positions
})

interface ChampionMarqueeItem extends Champion {
  winner: ChampionElement | null
  loser: ChampionElement | null
}

const championMarqueeItems = computed<ChampionMarqueeItem[]>(() => {
  const normalized = champions.value.map((champion) => {
    const candidates = [champion.left, champion.right].filter((candidate): candidate is ChampionElement => Boolean(candidate))
    return {
      ...champion,
      winner: candidates.find((candidate) => candidate.is_winner) ?? candidates[0] ?? null,
      loser: candidates.find((candidate) => !candidate.is_winner) ?? candidates[1] ?? null,
    }
  })
  return [...normalized, ...normalized]
})

watch([sort, activeKeyword, () => route.meta.viewKey], () => {
  if (route.meta.viewKey !== 'home') return
  searchInput.value = activeKeyword.value
  const nextRequestKey = `${sort.value}:${activeKeyword.value}`
  if (nextRequestKey === lastLoadedRequestKey) {
    if (pendingResetRequestKey && pendingResetRequestKey !== nextRequestKey) {
      requestVersion += 1
      pendingResetRequestKey = null
      loading.value = false
      refreshing.value = false
    }
    return
  }
  void loadPosts(true)
}, { immediate: true })
void loadHomeExtras()

async function loadPosts(reset: boolean): Promise<void> {
  const version = ++requestVersion
  const requestKey = `${sort.value}:${activeKeyword.value}`
  const refreshInPlace = reset && lastLoadedRequestKey !== null
  if (reset) {
    pendingResetRequestKey = requestKey
    loading.value = !refreshInPlace
    refreshing.value = refreshInPlace
    loadError.value = false
    loadMoreError.value = false
  } else {
    loadingMore.value = true
    loadMoreError.value = false
  }
  try {
    const result = await service.posts({
      sortBy: sort.value,
      range: 'week',
      keyword: activeKeyword.value,
      page: reset ? 1 : postsPage.value.page + 1,
    })
    if (version !== requestVersion) return
    if (reset) {
      postsPage.value = result
      lastLoadedRequestKey = requestKey
    } else {
      const existingSerials = new Set(postsPage.value.items.map((post) => post.serial))
      postsPage.value = {
        ...result,
        items: [...postsPage.value.items, ...result.items.filter((post) => !existingSerials.has(post.serial))],
      }
    }
  } catch {
    if (version === requestVersion) {
      if (reset) {
        if (!refreshInPlace) loadError.value = true
      } else {
        loadMoreError.value = true
      }
    }
  } finally {
    if (version === requestVersion) {
      if (reset) pendingResetRequestKey = null
      loading.value = false
      refreshing.value = false
      loadingMore.value = false
    }
  }
}

async function loadHomeExtras(): Promise<void> {
  if (extrasRequestStarted) return
  extrasRequestStarted = true
  const [tagsResult, carouselResult, championsResult] = await Promise.allSettled([
    service.hotTags(),
    service.carouselItems(),
    service.champions(),
  ])
  if (tagsResult.status === 'fulfilled') {
    tags.value = Object.entries(tagsResult.value)
      .map(([name, count]) => ({ name, count }))
      .sort((left, right) => right.count - left.count || left.name.localeCompare(right.name))
  }
  if (carouselResult.status === 'fulfilled') {
    carouselItems.value = carouselResult.value
    activeCarouselIndex.value = 0
  }
  if (championsResult.status === 'fulfilled') champions.value = championsResult.value
}

function submitSearch(): void {
  updateSearch(searchInput.value)
}

function selectTag(tag: string): void {
  searchInput.value = tag
  updateSearch(tag)
}

function clearSearch(): void {
  searchInput.value = ''
  updateSearch('')
}

function updateSearch(keyword: string): void {
  const query = { ...route.query }
  const normalized = keyword.trim().slice(0, 255)
  delete query.q
  if (normalized) query.k = normalized
  else delete query.k
  void router.push({ path: route.path, query })
}

function loadMorePosts(): void {
  if (!loadingMore.value && hasMorePosts.value) void loadPosts(false)
}

function gameURL(serial: string): string {
  return localizedPath(`/g/${encodeURIComponent(serial)}`, locale.value)
}

function rankURL(serial: string): string {
  return localizedPath(`/r/${encodeURIComponent(serial)}`, locale.value)
}

function browseURL(path: '/hot' | '/new'): string {
  const localized = localizedPath(path, locale.value)
  return activeKeyword.value
    ? `${localized}?${new URLSearchParams({ k: activeKeyword.value })}`
    : localized
}

function formatNumber(value: number): string {
  const language = locale.value === 'zh_TW' ? 'zh-TW' : locale.value
  return new Intl.NumberFormat(language, { notation: value >= 10_000 ? 'compact' : 'standard' }).format(value)
}

function isVideoThumbnail(url: string | null | undefined): boolean {
  return Boolean(url && /\.mp4(?:$|[?#])/i.test(url))
}

function voteCardImage(element: Parameters<typeof preferredElementImage>[0]): string {
  return preferredElementImage(element) || defaultPreviewImage
}

function useDefaultImage(event: Event): void {
  const image = event.currentTarget
  if (!(image instanceof HTMLImageElement) || image.dataset.fallbackApplied === 'true') return
  image.dataset.fallbackApplied = 'true'
  image.src = defaultPreviewImage
}

function showPreviousCarouselItem(): void {
  if (!carouselItems.value.length) return
  activeCarouselIndex.value = (activeCarouselIndex.value - 1 + carouselItems.value.length) % carouselItems.value.length
}

function showNextCarouselItem(): void {
  if (!carouselItems.value.length) return
  activeCarouselIndex.value = (activeCarouselIndex.value + 1) % carouselItems.value.length
}
</script>

<template>
  <div class="home-dashboard-layout">
    <aside class="home-discovery-rail">
