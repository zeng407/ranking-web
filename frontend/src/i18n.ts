/**
 * Single source of truth for locales.
 *
 * Adding a language means adding one entry here plus its `messages` block.
 * Nothing in the UI, the router or the language switcher enumerates locales,
 * so no component has to change.
 *
 * `code` keeps the existing Laravel translation keys (zh_TW / en / ja) and
 * `prefix` keeps the public URL segments already in use (zh-tw / en / ja), so
 * neither the translation files nor any live URL moves.
 */
export interface LocaleDefinition {
  /** Internal locale key, also the translation-file name. */
  readonly code: string
  /** Public URL segment; lowercase BCP 47-style. */
  readonly prefix: string
  /** Native name shown in the language switcher. */
  readonly label: string
  /** Value for the `lang` attribute. */
  readonly htmlLang: string
}

export const localeDefinitions = [
  { code: 'zh_TW', prefix: 'zh-tw', label: '繁體中文', htmlLang: 'zh-Hant' },
  { code: 'en', prefix: 'en', label: 'English', htmlLang: 'en' },
  { code: 'ja', prefix: 'ja', label: '日本語', htmlLang: 'ja' },
] as const satisfies readonly LocaleDefinition[]

export type Locale = (typeof localeDefinitions)[number]['code']
export type MessageKey = keyof typeof messages.zh_TW

export const defaultLocale: Locale = 'zh_TW'

export const supportedLocales: readonly Locale[] = localeDefinitions.map((definition) => definition.code)

const definitionsByCode = new Map<string, LocaleDefinition>(
  localeDefinitions.map((definition): [string, LocaleDefinition] => [definition.code, definition]),
)

export function localeDefinition(locale: Locale): LocaleDefinition {
  return definitionsByCode.get(locale) ?? localeDefinitions[0]
}

function escapeForRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/** Regex alternation of URL prefixes (`zh-tw|en|ja`) for route definitions. */
export const localePrefixPattern = localeDefinitions
  .map((definition) => escapeForRegExp(definition.prefix))
  .join('|')

/** Regex alternation of locale codes (`zh_TW|en|ja`) for legacy /lang redirects. */
export const localeCodePattern = localeDefinitions
  .map((definition) => escapeForRegExp(definition.code))
  .join('|')

const localePrefixExpression = new RegExp(`^/(?:${localePrefixPattern})(?=/|$)`)

/** Strips a leading locale segment, so `/ja/donate` becomes `/donate`. */
export function pathWithoutLocale(path: string): string {
  return path.replace(localePrefixExpression, '') || '/'
}

