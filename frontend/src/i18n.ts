export function normalizeLocale(value: unknown): Locale {
  if (typeof value !== 'string') return defaultLocale
  if (supportedLocales.includes(value as Locale)) return value as Locale

  const normalizedValue = value.toLowerCase()
  const match = localeDefinitions.find((definition) => definition.prefix === normalizedValue)

  return match ? match.code : defaultLocale
}

export function localizedPath(path: string, locale: Locale): string {
  const normalizedPath = path === '/' ? '/' : `/${path.replace(/^\/+|\/+$/g, '')}`
  return `/${localeDefinition(locale).prefix}${normalizedPath}`
}

export function localePrefix(locale: Locale): string {
  return localeDefinition(locale).prefix
}

/** Native language name for the switcher. */
export function localeLabel(locale: Locale): string {
  return localeDefinition(locale).label
}

export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages.zh_TW[key]
}

export function htmlLanguage(locale: Locale): string {
  return localeDefinition(locale).htmlLang
}
